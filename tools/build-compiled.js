// Records real compiler/runtime output for every slot combination of every 'cmp' challenge and every compare snippet.
// Usage: node tools/build-compiled.js [ids]   -> writes challenges/compiled-data.js
const fs = require('fs'), os = require('os'), path = require('path'), cp = require('child_process');
const ctx = require('./loadch.js')();
const JAVA = path.join(os.homedir(), 'tools/jdk-21.0.13+9/bin');
const TSC = '/tmp/tsx/node_modules/.bin/tsc';
function sh(cmd, args, cwd) {
  const r = cp.spawnSync(cmd, args, { cwd, encoding: 'utf8', timeout: 60000, input: '', env: Object.assign({}, process.env, { NO_COLOR: '1', TERM: 'dumb' }) });
  return { code: r.status === null ? (r.signal === 'SIGABRT' ? 134 : 1) : r.status, out: r.stdout || '', err: r.stderr || '' };
}
const LANGS = {
  cpp: { file: 'main.cpp', build: d => sh('python3', ['-m', 'ziglang', 'c++', '-std=c++17', '-fno-color-diagnostics', '-o', 'main', 'main.cpp'], d), run: d => sh('./main', [], d) },
  java: { file: 'Main.java', build: d => sh(JAVA + '/javac', ['Main.java'], d), run: d => sh(JAVA + '/java', ['Main'], d) },
  rust: { file: 'main.rs', build: d => sh('rustc', ['--edition', '2021', '--color', 'never', '-o', 'main', 'main.rs'], d), run: d => sh('./main', [], d) },
  go: { file: 'main.go', build: d => sh('go', ['build', '-o', 'main', 'main.go'], d), run: d => sh('./main', [], d) },
  ts: { file: 'main.ts', build: d => { const r = sh(TSC, ['--strict', '--target', 'es2020', '--pretty', 'false', 'main.ts'], d); r.err = r.out + r.err; r.out = ''; return r; }, run: d => sh('node', ['main.js'], d) },
  bash: { file: 'script.sh', run: d => sh('bash', ['script.sh'], d) },
  py: { file: 'main.py', run: d => sh('python3', ['main.py'], d) },
  js: { file: 'main.js', run: d => sh('node', ['main.js'], d) },
};
function clean(s, d) { return s.split(d + '/').join('').split(d).join('.').replace(/\x1b\[[0-9;]*m/g, '').replace(/^error: the following command failed[\s\S]*$/m, '').replace(/\n{3,}/g, '\n\n').replace(/\s+$/, s.trim() ? '\n' : ''); }
function record(lang, src) {
  const L = LANGS[lang], d = fs.mkdtempSync(path.join(os.tmpdir(), 'ddc-'));
  fs.writeFileSync(path.join(d, L.file), src);
  let err = '';
  if (L.build) { const b = L.build(d); err = clean(b.err, d); if (b.code !== 0) { fs.rmSync(d, { recursive: true, force: true }); return { ok: false, phase: 'compile', out: '', err, code: b.code }; } }
  const r = L.run(d); fs.rmSync(d, { recursive: true, force: true });
  err = err + clean(r.err, d);
  return { ok: r.code === 0, phase: r.code === 0 ? 'ok' : 'run', out: r.out, err, code: r.code };
}
function combos(ch) {
  const keys = Object.keys(ch.slots || {}).sort(); let out = [{}];
  keys.forEach(k => { const s = ch.slots[k], opts = s.o || s; const next = []; out.forEach(c => opts.forEach(v => next.push(Object.assign({}, c, { [k]: v })))); out = next; });
  return { keys, list: out };
}
const fill = (ch, vals) => ch.code.replace(/\{\{(\w+)\}\}/g, (_, k) => vals[k] === undefined ? '' : String(vals[k]));
const DB = {}, only = process.argv[2] ? process.argv[2].split(',') : null;
let prev = {}; try { const t = fs.readFileSync(path.join(__dirname, '../challenges/compiled-data.js'), 'utf8'); prev = JSON.parse(t.slice(t.indexOf('{'), t.lastIndexOf('}') + 1)); } catch (e) { }
ctx.CHD.list.filter(c => c.sb === 'cmp').forEach(ch => {
  if (only && only.indexOf(ch.id) < 0) { Object.keys(prev).forEach(k => { if (k.split(/[|#]/)[0] === ch.id) DB[k] = prev[k]; }); return; }
  const { keys, list } = combos(ch);
  list.forEach(vals => { const key = ch.id + '|' + keys.map(k => vals[k]).join('|'); DB[key] = record(ch.lang || 'cpp', fill(ch, vals)); process.stdout.write('.'); });
  (ch.compare || []).forEach((c, i) => { DB[ch.id + '#' + i] = record(c.lang, c.code); process.stdout.write('c'); });
  console.log(' ' + ch.id);
});
(ctx.DRILLS ? ctx.DRILLS.gens : []).filter(g => g.sb === 'cmp').forEach(g => {
  for (let seed = 0; seed < g.k; seed++) {
    const ch = ctx.DRILLS.make(g.id, seed);
    if (only && only.indexOf(g.id) < 0) { Object.keys(prev).forEach(k => { if (k.split('|')[0] === ch.id) DB[k] = prev[k]; }); continue; }
    const { keys, list } = combos(ch);
    list.forEach(vals => { const key = ch.id + '|' + keys.map(k => vals[k]).join('|'); DB[key] = record(ch.lang || 'cpp', fill(ch, vals)); process.stdout.write('.'); });
    console.log(' ' + ch.id);
  }
});
fs.writeFileSync(path.join(__dirname, '../challenges/compiled-data.js'), '// Generated by tools/build-compiled.js from real toolchains: clang 22 (zig c++), javac/java 21, rustc 1.85, go 1.27, tsc 7 + node 24, bash 5, python 3.13.\n// Do not edit by hand.\nwindow.COMPILED = ' + JSON.stringify(DB) + ';\n');
console.log(Object.keys(DB).length, 'records');
